"""Build src/data/seenSensors.ts from findings sent back by the app.

Input: replica/findings/<car>/*.json, copies of the files the app put in the
caristini-data repo (findings/<VIN>/...). Each file's data holds the sensor
keys (header-identifier) that car answered: data.sensorsFound (kinds 'saved'
and 'learn') or data.found (kind 'sensors').

Output: one entry per make group and platform with the union of keys, so a new
car of the same make is asked those first. VINs are not written out.
Run: python scripts/gen_seen_sensors.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FINDINGS = ROOT / "replica" / "findings"
OUT = ROOT / "src" / "data" / "seenSensors.ts"


def main():
    seen = {}
    cars = {}
    for f in sorted(FINDINGS.glob("*/*.json")):
        doc = json.loads(f.read_text(encoding="utf-8"))
        data = doc.get("data") or {}
        car = data.get("car") or {}
        group = car.get("group") or ("vag" if doc.get("vin", "")[:3] in {"WAU", "WVW", "WV1", "WV2", "TMB", "VSS", "TRU", "WUA"} else None)
        keys = data.get("sensorsFound") or data.get("found") or []
        if not group or not keys:
            continue
        k = (group, car.get("platform"), car.get("brand"))
        seen.setdefault(k, set()).update(keys)
        cars.setdefault(k, set()).add(doc.get("vin", "")[-6:])
    rows = [
        {"group": g, "platform": p, "brand": b, "cars": len(cars[(g, p, b)]), "keys": sorted(v)}
        for (g, p, b), v in sorted(seen.items(), key=lambda x: (x[0][0], x[0][1] or "", x[0][2] or ""))
    ]
    OUT.write_text(
        "// Generated by scripts/gen_seen_sensors.py from findings sent back by the\n"
        "// app (replica/findings). Do not edit by hand.\n"
        "export const SEEN_SENSORS: { group: string; platform: string | null; brand: string | null; cars: number; keys: string[] }[] = "
        + json.dumps(rows, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
        newline="\n",
    )
    for r in rows:
        print(f"{r['group']} {r['platform']}: {len(r['keys'])} sensors from {r['cars']} car(s)")


if __name__ == "__main__":
    main()

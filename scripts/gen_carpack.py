"""Build src/data/cars/leonCupra.ts from the researched JSON in replica/.

Inputs (written by the research, every item with its public source):
  replica/cupra-parts.json      [{name, group, oem, notes, confidence, source}]
  replica/cupra-reference.json  {fluids, specs, schedule, faults, recalls, vin}
  replica/cupra-faults-reported.json  faults from owner and garage pages only
                                      (Low), shown as "Owners report"

Only High and Medium items are kept. Run: python scripts/gen_carpack.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPLICA = ROOT / "replica"
OUT = ROOT / "src" / "data" / "cars" / "leonCupra.ts"

KEEP = {"High", "Medium"}


# The workshop manual writes the gap as "0.8 - 0.1 mm", which reads as a typo;
# left out until checked against the plug box or a second source.
DROP = {"Spark plug gap"}


def keep(rows):
    return [
        r for r in rows
        if r.get("confidence") in KEEP and r.get("source", {}).get("url") and r.get("item") not in DROP
    ]


def part(r):
    out = {"name": r["name"], "group": r["group"], "oem": r["oem"], "confidence": r["confidence"], "source": r["source"]}
    if r.get("notes"):
        out["notes"] = r["notes"]
    return out


def fact(r):
    return {"item": r["item"], "value": r["value"], "confidence": r["confidence"], "source": r["source"]}


def fault(r):
    return {
        "title": r["title"],
        "symptoms": r.get("symptoms", ""),
        "codes": r.get("codes", []),
        "cause": r.get("cause", ""),
        "fix": r.get("fix", ""),
        "confidence": r["confidence"],
        "source": r["source"],
    }


def main():
    parts = json.loads((REPLICA / "cupra-parts.json").read_text(encoding="utf-8"))
    ref = json.loads((REPLICA / "cupra-reference.json").read_text(encoding="utf-8"))
    reported = json.loads((REPLICA / "cupra-faults-reported.json").read_text(encoding="utf-8"))
    pack = {
        "id": "seat-leon-1p-cupra-bwj",
        "title": "SEAT Leon Cupra 2.0 TFSI (BWJ)",
        "basis": "Leon II (1P1) Cupra, 2.0 TFSI engine BWJ, 6-speed manual 02Q, UK",
        "researched": "12 Nov 2026",
        "wmi": "VSS",
        "modelCode": "1P",
        "years": [2007, 2008, 2009],
        "engineCode": "BWJ",
        "vins": [],
        "parts": [part(r) for r in keep(parts)],
        "fluids": [fact(r) for r in keep(ref.get("fluids", []))],
        "specs": [fact(r) for r in keep(ref.get("specs", []))],
        "schedule": [fact(r) for r in keep(ref.get("schedule", []))],
        "faults": [fault(r) for r in keep(ref.get("faults", []))]
        + [fault(r) for r in reported if r.get("source", {}).get("url")],
        "recalls": [r for r in ref.get("recalls", []) if r.get("source", {}).get("url")],
    }
    body = json.dumps(pack, ensure_ascii=False, indent=2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/gen_carpack.py from replica/cupra-parts.json and\n"
        "// replica/cupra-reference.json. Do not edit by hand.\n"
        "import type { CarPack } from './index';\n\n"
        f"export const LEON_CUPRA: CarPack = {body};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT.relative_to(ROOT)}: {len(pack['parts'])} parts, {len(pack['fluids'])} fluids, "
          f"{len(pack['specs'])} specs, {len(pack['schedule'])} schedule, {len(pack['faults'])} faults, "
          f"{len(pack['recalls'])} recalls")


if __name__ == "__main__":
    main()

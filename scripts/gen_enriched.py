"""Build src/coding/enriched.ts from replica/a6-enrich.json (researched
12 Nov 2026 from public sources; see replica/a6-enrich.md). Keeps settings
rated high or medium that have a source URL, and module notes for Knowledge.
Run: python scripts/gen_enriched.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "replica" / "a6-enrich.json"
OUT = ROOT / "src" / "coding" / "enriched.ts"
# Logins the notes give for a setting (the parking aid MMI graphic, 71679).
LOGINS = {"a6e-ops-mmi": 71679}


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    items = []
    for s in d.get("settings", []):
        if s.get("confidence") not in ("high", "medium"):
            continue
        if not any(x.get("url") for x in s.get("sources", [])):
            continue
        if s["id"] in LOGINS:
            s["login"] = LOGINS[s["id"]]
        items.append(s)
    modules = [{k: m.get(k) for k in ("id", "part", "plainName", "what", "notes", "sources")} for m in d.get("modules", [])]
    OUT.write_text(
        "// Generated by scripts/gen_enriched.py from replica/a6-enrich.json. Do not edit by hand.\n"
        "import type { CodingItem } from './items';\n\n"
        f"export const ENRICHED_ITEMS: CodingItem[] = {json.dumps(items, ensure_ascii=False, indent=1)};\n\n"
        "// What each module of the 2012 A6 C7 (MLB) is, from public sources.\n"
        "export const ENRICHED_MODULES: { id: string; part: string | null; plainName: string; what: string; notes?: string | null; sources: { label: string; url: string }[] }[] = "
        f"{json.dumps(modules, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(items)} settings, {len(modules)} modules")


if __name__ == "__main__":
    main()

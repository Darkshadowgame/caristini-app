/**
 * Fuse boxes and manual links for the four supported cars.
 *
 * Copied from replica/fuses-sources.md (research note, 11 Nov 2026).
 * Facts only: fuse number, rating and short function from the owner's
 * manual named for each car. Every box cites its source URL.
 */

export interface Fuse {
  id: string; // as printed: "F41", "B7", "12"
  amps: number[] | null; // [20]; [5, 25] for "5/25"; null when the table shows "-"
  fn: string; // short function text from the table
  label?: string; // Mazda box code, when the table has one
  varies?: boolean; // table marks it as equipment-dependent (var = Y)
  notUsed?: boolean;
}

export interface FuseBox {
  id: string; // e.g. 'AUDI-DRV' as in the md headings
  name: string; // e.g. "Dash panel, driver's side"
  location: string; // from the Locations and access table
  access: string; // from the Locations and access table
  note?: string; // box-level caveats
  sourceUrl: string;
  fuses: Fuse[];
}

export interface ManualLink {
  label: string;
  url: string;
  official: boolean; // false for mirrors / third-party copies
  note?: string; // access or price notes
}

export interface FuseCar {
  id: 'audi-a6-c7' | 'seat-leon-1p' | 'ford-focus-mk3' | 'mazda6-gj';
  title: string;
  group: 'vag' | 'ford' | 'mazda';
  brand: string;
  // Lower-case words; the app matches a saved car when its model contains one.
  models: string[];
  manual: string;
  caveats: string[];
  boxes: FuseBox[];
  links: ManualLink[];
}


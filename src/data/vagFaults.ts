/**
 * Meaning for a VAG 5-digit fault number. Accepts '00256', '256' or
 * '16684'; returns undefined when the number is unknown.
 */
export function vagFaultText(code: string): string | undefined {
  const digits = String(code).trim().replace(/\D/g, '');
  if (digits.length === 0 || digits.length > 5) return undefined;
  const key = digits.padStart(5, '0');
  const known = vagFaults()[key];
  if (known !== undefined) return known;
  const n = Number(key);
  // 16384 + 1024 x (second digit) + last 3 digits: P0xxx to P3xxx.
  if (n >= 16384 && n < 16384 + 4 * 1024) {
    const k = Math.floor((n - 16384) / 1024);
    const rest = (n - 16384) % 1024;
    if (rest <= 999) return `Engine: P${k}${String(rest).padStart(3, '0')}`;
  }
  return undefined;
}
